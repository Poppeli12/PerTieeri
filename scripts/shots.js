const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 1 });
  p.on('pageerror', e => console.log('PAGEERROR', e.message));
  p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
  await p.goto('http://localhost:8099');
  await p.waitForTimeout(1500);
  await p.screenshot({ path: 'scripts/s1-home.png' });
  await p.getByText('Per Tieeri', { exact: true }).last().click();
  await p.waitForTimeout(1200);
  await p.screenshot({ path: 'scripts/s2-onb.png' });
  await p.getByText('Aloitetaan').click(); await p.waitForTimeout(500);
  await p.getByText('Kyllä, 21').click(); await p.waitForTimeout(400);
  await p.getByText('Opiskelen ja käyn töissä').click(); await p.waitForTimeout(400);
  await p.getByText('Yksin vuokralla').click(); await p.waitForTimeout(400);
  await p.getByText('Puskuri yllätyksiin').click(); await p.waitForTimeout(400);
  await p.getByText('Liikunta ja harrastukset').click(); await p.getByText('Jatka').click(); await p.waitForTimeout(400);
  await p.getByText('Opettaen ja perustellen').click();
  await p.waitForTimeout(7000);
  await p.screenshot({ path: 'scripts/s3-chat.png' });
  await p.getByText('Kolme rahakoria', { exact: true }).first().click();
  await p.waitForTimeout(4000);
  await p.screenshot({ path: 'scripts/s4-baskets.png' });
  await p.getByText('Oma talous').click(); await p.waitForTimeout(2500);
  await p.screenshot({ path: 'scripts/s5-insights.png', fullPage: false });
  await p.mouse.wheel(0, 1300); await p.waitForTimeout(1500);
  await p.screenshot({ path: 'scripts/s6-insights2.png' });
  await b.close();
})();
